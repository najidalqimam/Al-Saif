function flatten(nodes: Input[], parentId: string | null, level: 1 | 2 | 3): CatalogCategory[] {
  return nodes.flatMap((node, index) => {
    const current: CatalogCategory = {
      id: node.slug,
      slug: node.slug,
      nameAr: node.ar,
      nameEn: node.en,
      descriptionAr: node.textAr,
      descriptionEn: node.textEn,
      image: node.image || IMAGES[node.slug] || "",
      icon: node.icon ?? "grid",
      parentId,
      level,
      sort: index + 1,
      active: node.active !== false,
      featured: Boolean(node.featured),
    };
    const nextLevel = (level + 1) as 2 | 3;
    return [current, ...(node.children && level < 3 ? flatten(node.children, node.slug, nextLevel) : [])];
  });
}

